// Запасные «мозги» — работают без ключа Anthropic.
//
// Подбор реплики по ключевым словам, отдельный банк фраз на каждого
// персонажа (mcqueen, mater, doc). Для дошкольника этого хватает: персонаж
// узнаётся по голосу и манере, а разговор держится на встречных вопросах.
//
// Важно понимать границы этого движка: он смотрит на отдельные слова во
// фразе, а не на смысл целиком. «Обзывалки» он ловит по конкретным словам
// («тупой», «дурак» и т.п.), а не потому что «понял», что его оскорбили.
// Настоящее понимание контекста — только с ANTHROPIC_API_KEY (см. app.js).

// ---------------------------------------------------------- границы слова
// Обычный JS \b не работает с кириллицей (там граница слова определена
// только для латиницы и цифр). Из-за этого короткие триггеры ловили
// подстроки внутри других слов: «пока» находилось внутри «покакал»,
// «док» — внутри «документ». Чтобы этого не было, однословные триггеры
// оборачиваем в ручные lookaround-границы по кириллице/латинице.
function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function triggers(...words) {
  const parts = words.map((w) =>
    /\s/.test(w)
      ? escapeRegExp(w) // фраза из нескольких слов — пробелы уже дают границу
      : `(?<![а-яёa-z0-9])${escapeRegExp(w)}(?![а-яёa-z0-9])`
  );
  return new RegExp(parts.join('|'), 'iu');
}

// -------------------------------------------------------------- имя ребёнка
// Единственное место, где движок реально «понимает смысл», а не ловит слово:
// вытаскивает имя из явного представления («меня зовут Оливия») или из
// короткого ответа на прямой вопрос «как тебя зовут / кто звонит».
function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
}

function extractIntroducedName(text) {
  const patterns = [
    /меня зовут\s+([a-zа-яё]{2,20})/iu,
    /зовут меня\s+([a-zа-яё]{2,20})/iu,
    /(?:моё|мое) имя\s+([a-zа-яё]{2,20})/iu,
    /я\s*[-—]\s*([a-zа-яё]{2,20})/iu,
  ];
  for (const re of patterns) {
    const m = text.match(re);
    if (m) return capitalize(m[1]);
  }
  return null;
}

// Персонаж только что спросил, кто звонит / как зовут.
function assistantAskedForName(history) {
  const lastAssistant = [...(history || [])].reverse().find((m) => m.role === 'assistant');
  if (!lastAssistant) return false;
  return /зовут|звать|имя|кто это звонит|кто звонит/iu.test(lastAssistant.content);
}

// Похоже на голое имя: одно-два слова, только буквы, не системное слово типа «да».
function looksLikeBareName(text) {
  const t = text.trim();
  if (!/^[a-zа-яё]{2,20}(\s[a-zа-яё]{2,20})?$/iu.test(t)) return false;
  return !/^(да|нет|ага|неа|привет|пока|алло|ало)$/iu.test(t);
}

function matchesAnyRule(bank, text) {
  return Object.values(bank).some((rule) => rule.test.test(text));
}

