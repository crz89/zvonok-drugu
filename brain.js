// Помним, какую реплику отдали последней (на персонажа), чтобы не повторяться.
const cursor = new Map();

function pick(key, list) {
  const previous = cursor.get(key) ?? -1;
  let index = Math.floor(Math.random() * list.length);
  if (list.length > 1 && index === previous) index = (index + 1) % list.length;
  cursor.set(key, index);
  return list[index];
}

/**
 * Подбирает реплику персонажа на фразу ребёнка.
 * @param {string} characterId — 'mcqueen' | 'mater' | 'doc'
 * @param {string} userText — распознанная речь ребёнка (полное предложение)
 * @param {Array<{role:string, content:string}>} history — вся история звонка,
 *   нужна только чтобы понять, спрашивал ли персонаж только что имя.
 * @returns {string}
 */
export function localReply(characterId, userText, history = []) {
  const bank = BANKS[characterId] ?? BANKS.mcqueen;
  const fallback = FALLBACK[characterId] ?? FALLBACK.mcqueen;
  const text = String(userText || '').trim();

  // 1) Ребёнок явно представился — это важнее любых тематических триггеров.
  const introduced = extractIntroducedName(text);
  if (introduced) return nameReply(characterId, introduced);

  // 2) Персонаж только что спросил «как тебя зовут» / «кто звонит», а в
  //    ответ пришло короткое слово без своих триггеров — это и есть имя.
  if (assistantAskedForName(history) && looksLikeBareName(text) && !matchesAnyRule(bank, text)) {
    return nameReply(characterId, capitalize(text));
  }

  // 3) Обычные тематические правила.
  for (const [name, rule] of Object.entries(bank)) {
    if (rule.test.test(text)) return pick(characterId + ':' + name, rule.replies);
  }
  return pick(characterId + ':__fallback__', fallback);
}
